// Regenerate extension/lib/hanzi-data.js from OpenCC's TSCharacters.txt (Apache-2.0):
//   curl -sSfLO https://raw.githubusercontent.com/BYVoid/OpenCC/master/data/dictionary/TSCharacters.txt
//   node scripts/gen-hanzi.mjs TSCharacters.txt
// Only the first (default) simplified form of each traditional character is kept: search folds both
// sides to one form, so one-to-one is all it needs (D-031).
import { readFileSync, writeFileSync } from "node:fs";

const src = process.argv[2];
if (!src) throw new Error("usage: node scripts/gen-hanzi.mjs path/to/TSCharacters.txt");
let trad = "";
let simp = "";
for (const line of readFileSync(src, "utf8").split("\n")) {
  if (!line.trim() || line.startsWith("#")) continue;
  const [k, v] = line.split("\t");
  const first = v?.trim().split(/\s+/)[0];
  if (!k || !first || [...k].length !== 1 || [...first].length !== 1 || k === first) continue;
  trad += k;
  simp += first;
}
const out = `// Generated by scripts/gen-hanzi.mjs from OpenCC TSCharacters.txt — do not edit.
// OpenCC: https://github.com/BYVoid/OpenCC, Copyright BYVoid, Apache License 2.0.
// TRAD[i] (traditional) → SIMP[i] (simplified), by code point. ${[...trad].length} pairs.
export const TRAD = ${JSON.stringify(trad)};
export const SIMP = ${JSON.stringify(simp)};
`;
writeFileSync(new URL("../extension/lib/hanzi-data.js", import.meta.url), out);
console.log(`wrote ${[...trad].length} pairs`);
